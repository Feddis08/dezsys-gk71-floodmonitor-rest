/* Run with: JSDOM_PATH=/path/to/jsdom node tests/client.test.cjs (from static/). */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(process.env.JSDOM_PATH || '../.verify/node_modules/jsdom');
const root = path.join(__dirname, '..');
(async () => {
  const dom = new JSDOM(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), {
    url: 'http://localhost/', runScripts: 'outside-only', pretendToBeVisual: true
  });
  const w = dom.window;
  w.eval(fs.readFileSync(path.join(root, 'vendor/jquery-3.7.1.min.js'), 'utf8'));
  const $ = w.jQuery, requests = [];
  let tick, interval;
  w.setInterval = (fn, ms) => { tick = fn; interval = ms; return 1; };
  w.clearInterval = () => { tick = null; };
  $.ajax = options => {
    const deferred = $.Deferred();
    const xhr = deferred.promise({ options, status: 200, responseText: '', aborted: false });
    const originalDone = xhr.done;
    xhr.done = function (fn) { xhr.lateDone = fn; return originalDone.call(this, fn); };
    xhr.abort = () => { xhr.aborted = true; deferred.reject(xhr, 'abort'); };
    xhr.resolve = body => deferred.resolve(body);
    xhr.reject = (status, body) => { xhr.status = status; xhr.responseText = body; deferred.reject(xhr, 'error'); };
    requests.push(xhr);
    return xhr;
  };
  w.eval(fs.readFileSync(path.join(root, 'app.js'), 'utf8'));
  await new Promise(resolve => w.setTimeout(resolve, 20));
  const measurement = { stationId: 's1', timestamp: '2026-11-03T10:00:00Z', waterLevel: 1.2, flowRate: 3, rainfall: 4, temperature: 5, batteryLevel: 90, status: 'OK', warningLevel: 'WARNING' };
  const xml = object => Object.entries(object).map(([key, val]) => '<' + key + '>' + val + '</' + key + '>').join('');
  assert.equal(requests.length, 1);
  assert.equal(requests[0].options.headers.Accept, 'application/json');
  assert.equal(interval, 10000);
  tick(); assert.equal(requests.length, 1, 'no overlapping poll');
  requests[0].resolve(JSON.stringify([{ id: 's1', name: '<img src=x onerror=alert(1)>', river: 'Donau', isActive: true, location: { latitude: 48, longitude: 16 } }, { id: 's2', name: 'Zwei', river: 'Inn', isActive: false, location: 'Tirol' }]));
  assert.equal($('#station option').length, 2);
  assert.equal($('#station img').length, 0, 'station name is text, not HTML');
  assert.match($('#station-details').text(), /Aktiv: Ja/);
  assert.equal(requests.length, 3);
  requests[1].resolve(JSON.stringify(measurement)); requests[2].resolve(JSON.stringify([measurement]));
  assert.equal($('#latest dd').length, 9);
  assert.equal($('#history td').length, 9);
  assert.equal($('#history .warning').text(), 'WARNING');
  assert.equal($('#loading').prop('hidden'), true);
  $('#from').val('2026-11-03T09:00:00'); $('#to').val('2026-11-03T11:00:00');
  $('#warning').val('CRITICAL').trigger('change');
  const oldLatest = requests.at(-2), oldHistory = requests.at(-1);
  assert.equal(oldHistory.options.data.from, new Date('2026-11-03T09:00:00').toISOString());
  assert.equal(oldHistory.options.data.warningLevel, 'CRITICAL');
  $('#station').val('s2').trigger('change');
  assert.ok(oldLatest.aborted && oldHistory.aborted);
  oldLatest.lateDone(JSON.stringify(measurement)); oldHistory.lateDone(JSON.stringify([measurement]));
  assert.equal($('#history td').length, 0, 'stale station response ignored');
  assert.equal($('#latest dd').length, 0);
  $('#format').val('xml').trigger('change');
  assert.equal(requests.at(-1).options.headers.Accept, 'application/xml');
  requests.at(-1).resolve('<stations><station><id>s2</id><name>Zwei</name><river>Inn</river><isActive>false</isActive><location>Tirol</location></station></stations>');
  assert.equal($('#station').val(), 's2');
  assert.match($('#station-details').text(), /Aktiv: Nein/);
  requests.at(-2).resolve('<measurement>' + xml({ ...measurement, stationId: 's2', warningLevel: 'CRITICAL' }) + '</measurement>');
  requests.at(-1).resolve('<ArrayList><item>' + xml({ ...measurement, stationId: 's2', warningLevel: 'NORMAL' }) + '</item></ArrayList>');
  assert.equal($('#latest .critical').text(), 'CRITICAL');
  assert.equal($('#history .normal').text(), 'NORMAL');
  $('#refresh').trigger('click');
  requests.at(-2).resolve('<measurement>' + xml({ ...measurement, warningLevel: 'UNKNOWN' }) + '</measurement>');
  requests.at(-1).resolve('<measurements><measurement>' + xml(measurement) + '</measurement><measurement>' + xml({ ...measurement, warningLevel: 'UNKNOWN' }) + '</measurement></measurements>');
  assert.equal($('#history tr').length, 2, 'plural XML wrapper with repeated measurement elements');
  assert.equal($('#latest .unknown').text(), 'UNKNOWN');
  assert.equal($('#history .unknown').text(), 'UNKNOWN');
  $('#refresh').trigger('click');
  requests.at(-2).reject(404, '<problem><title>Keine Messung</title><detail>Noch keine Daten importiert.</detail></problem>');
  requests.at(-1).resolve('<measurements/>');
  assert.match($('#latest-error').text(), /HTTP 404: Keine Messung: Noch keine Daten importiert/);
  assert.match($('#history-message').text(), /Keine Messungen/);
  $('#refresh').trigger('click');
  requests.at(-2).resolve('<measurement><broken>');
  requests.at(-1).resolve(JSON.stringify([measurement]));
  assert.match($('#latest-error').text(), /nicht als XML/);
  assert.match($('#history-error').text(), /nicht als XML/, 'XML never falls back to JSON');
  $('#format').val('json').trigger('change');
  requests.at(-1).reject(500, JSON.stringify({ title: 'Datenbankfehler', detail: '<script>alert(1)</script>' }));
  assert.match($('#station-error').text(), /Datenbankfehler: <script>/);
  assert.equal($('#station-error script').length, 0);
  $('#refresh').trigger('click'); requests.at(-1).resolve('[]');
  assert.match($('#station-message').text(), /noch keine Stationen/);
  $('#refresh').trigger('click'); requests.at(-1).resolve(JSON.stringify([{ id: 's1', name: 'Eins', river: 'Inn', isActive: true, location: 'Tirol' }]));
  requests.at(-2).resolve(''); requests.at(-1).resolve('[]');
  assert.match($('#latest-message').text(), /noch keine Messung/);
  $('#from').val('2026-11-04T10:00:00').trigger('change');
  assert.match($('#filter-error').text(), /nicht nach/);
  const count = requests.length; tick(); assert.equal(requests.length, count, 'invalid filter makes no request');
  $('#from').val('').trigger('change');
  const stale = requests.at(-1);
  $('#limit').val('20').trigger('input'); assert.ok(stale.aborted);
  stale.lateDone(JSON.stringify([measurement])); assert.equal($('#history td').length, 0, 'editing filter invalidates responses immediately');
  $('#automatic').prop('checked', false).trigger('change'); assert.equal(tick, null);
  $('#interval').val('0').trigger('change'); assert.match($('#settings-error').text(), /1 bis 3600/);
  $('#interval').val('5'); $('#automatic').prop('checked', true).trigger('change'); assert.equal(interval, 5000);
  console.log('PASS: actual vendored jQuery + shipped JS in jsdom; JSON/XML, all 9 measurement fields, station fields, XSS-safe text, XML wrappers, error bodies, empty datasets, timezone filters, 10s/configurable polling, no overlap, aborted/stale response guards, filter edit invalidation.');
  dom.window.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
